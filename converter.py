def traditional_to_simplified(text):
    """将繁体中文转换为简体中文"""
    if HAS_OPENCC:
        # 使用OpenCC进行准确转换
        return cc.convert(text)
    else:
        # 使用简化对照表
        result = []
        for char in text:
            simplified = TRADITIONAL_TO_SIMPLIFIED.get(char, char)
            result.append(simplified)
        return ''.join(result)

def is_traditional(text):
    """检测文本是否包含繁体字"""
    if HAS_OPENCC:
        # 使用OpenCC检测
        simplified = cc.convert(text)
        return simplified != text
    else:
        # 使用对照表检测
        for char in text:
            if char in TRADITIONAL_TO_SIMPLIFIED:
                return True
        return False
