conn = sqlite3.connect(str(DB))
c = conn.cursor()

count = 0
skipped = 0
for title, author, dynasty, content, theme, form, chars in CURATED2:
    # 存在性检查（用第一句）
    first = content.split('\n')[0][:10]
    c.execute("SELECT COUNT(*) FROM poems WHERE content LIKE ? AND collection='名篇精选'", (f'%{first}%',))
    if c.fetchone()[0]:
        print(f"  跳过（已存在）: 《{title}》")
        skipped += 1
        continue
    word_count = len(content.replace('\n', ''))
    line_count = content.count('\n') + 1
    c.execute('''
        INSERT INTO poems (title, author, dynasty, content, source, theme, poem_form,
                           chars_per_line, line_count, word_count, collection)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    ''', (title, author, dynasty, content, '名篇精选', theme, form, chars, line_count, word_count, '名篇精选'))
    count += 1

conn.commit()
print(f"\n补录: {count}首, 跳过: {skipped}首")

# 验证
c.execute("SELECT COUNT(*) FROM poems WHERE collection='名篇精选'")
print(f"名篇精选共计: {c.fetchone()[0]}首")

# 重建FTS
conn.execute("INSERT INTO poems_fts(poems_fts) VALUES('rebuild')")
