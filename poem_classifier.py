def classify_poem(title, content, author=""):
    """
    对诗词进行题材分类
    
    Args:
        title: 诗词标题
        content: 诗词内容
        author: 作者
    
    Returns:
        dict: {
            'primary': 主要题材,
            'secondary': 次要题材,
            'imagery': 主要意象,
            'confidence': 置信度
        }
    """
    # 使用jieba分词
    words = list(jieba.cut(f"{title} {content}"))
    text = " ".join(words)
    
    # 计算每个题材的匹配分数
    scores = {}
    
    # 传统七大题材
    for theme, info in THEME_KEYWORDS.items():
        score = 0
        
        # 标题关键词匹配（权重更高）
        for keyword in info.get('title_keywords', []):
            if keyword in title:
                score += 3
        
        # 内容关键词匹配
        for keyword in info['keywords']:
            if keyword in text:
                score += 1
        
        if score > 0:
            scores[theme] = score
    
    # 扩展题材
    for theme, info in EXTENDED_KEYWORDS.items():
        score = 0
        
        # 标题关键词匹配
        for keyword in info.get('title_keywords', []):
            if keyword in title:
                score += 3
        
        # 内容关键词匹配
        for keyword in info['keywords']:
            if keyword in text:
                score += 1
        
        if score > 0:
            scores[theme] = score
    
    # 意象分析
    imagery = []
    for img, keywords in IMAGERY_KEYWORDS.items():
        for keyword in keywords:
            if keyword in text:
                imagery.append(img)
                break
    
    # 排序
    sorted_scores = sorted(scores.items(), key=lambda x: x[1], reverse=True)
    
    # 获取主要和次要题材
    primary = sorted_scores[0][0] if sorted_scores else "其他"
    secondary = sorted_scores[1][0] if len(sorted_scores) > 1 else ""
    
    # 计算置信度
    total_score = sum(scores.values())
    confidence = sorted_scores[0][1] / total_score if total_score > 0 and sorted_scores else 0
    
    return {
        'primary': primary,
        'secondary': secondary,
        'imagery': imagery[:3],  # 最多3个意象
        'confidence': round(confidence, 2)
    }

def get_theme_description(theme):
    """获取题材描述"""
    if theme in THEME_KEYWORDS:
        return THEME_KEYWORDS[theme]['description']
    elif theme in EXTENDED_KEYWORDS:
        return EXTENDED_KEYWORDS[theme]['description']
    return ""

def get_theme_examples(theme):
    """获取题材示例"""
    if theme in THEME_KEYWORDS:
        return THEME_KEYWORDS[theme]['examples']
    elif theme in EXTENDED_KEYWORDS:
        return EXTENDED_KEYWORDS[theme]['examples']
    return ""

def get_all_themes():
    """获取所有题材分类"""
    themes = []
    themes.extend(THEME_KEYWORDS.keys())
    themes.extend(EXTENDED_KEYWORDS.keys())
    return themes

