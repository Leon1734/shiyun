def get_cipai_info(name):
    """获取词牌信息"""
    # 精确匹配
    if name in CIPAI_DICT:
        return CIPAI_DICT[name]
    
    # 模糊匹配（处理 "水调歌头·明月几时有" 这类）
    for cipai in CIPAI_DICT:
        if name.startswith(cipai) or cipai in name:
            return CIPAI_DICT[cipai]
    
    return None


def search_cipai(keyword):
    """搜索词牌"""
    results = []
    for name, info in CIPAI_DICT.items():
        if keyword in name:
            results.append((name, info))
            continue
        # 搜索别名
        for alias in info.get('别名', []):
            if keyword in alias:
                results.append((name, info))
                break
    return results


def get_all_cipai():
    """获取所有词牌名"""
    return sorted(CIPAI_DICT.keys())


